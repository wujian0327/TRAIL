//! Measure the BLS operations on one valid TRAIL path with prepared inputs.
use blst::min_sig::{AggregateSignature, PublicKey, Signature};
use blst::BLST_ERROR;
use clap::Parser;
use serde_json::json;
use std::fs::{self, File, OpenOptions};
use std::hint::black_box;
use std::io::{self, BufWriter, Write};
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Instant;
use trail::blockchain::path::{TransactionPaths, TRAIL_TX_PATH_DOMAIN};
use trail::blockchain::transaction::Transaction;
use trail::consensus::ValidatorRegistry;
use trail::tools::Hasher;
use trail::wallet::Wallet;

const HOPS: [usize; 6] = [1, 2, 4, 6, 8, 16];
const WARMUP: usize = 50;
const MIN_SAMPLES: usize = 1000;
const EPOCH: u64 = 7;

#[derive(Parser)]
#[command(about = "Time BLS signing, aggregation and one uncached verification of a TRAIL path")]
struct Args {
    #[arg(long, default_value_t = MIN_SAMPLES)]
    samples: usize,
    #[arg(long, default_value = "results/processed/bls_path_latency")]
    output_dir: PathBuf,
}

struct Fixture {
    wallets: Vec<Wallet>,
    hop_messages: Vec<Vec<u8>>,
    signer_keys: Vec<PublicKey>,
    aggregate: Signature,
}

impl Fixture {
    fn new(hops: usize) -> Self {
        let wallets: Vec<_> = (0..=hops)
            .map(|i| Wallet::new_deterministic(0x424c_5350_4154_4800 + hops as u64, i as u32))
            .collect();
        let proposer = &wallets[hops].address;
        let registry = ValidatorRegistry::from_wallets(&wallets).expect("distinct validators");
        let tx = Transaction::with_timestamp(
            proposer.clone(),
            hops as i64,
            1.0,
            1.0,
            wallets[0].clone(),
            false,
            1_700_000_000,
        );
        let mut route = TransactionPaths::new_with_epoch(tx.clone(), EPOCH);
        for edge in wallets.windows(2) {
            assert!(route.append_completed_hop(
                edge[1].address.clone(),
                edge[0].clone(),
                edge[1].clone()
            ));
        }
        let certificate = route
            .to_aggregated_signed_paths(&registry)
            .expect("registered path");
        assert!(certificate.verify_at_epoch_uncached(&tx, proposer, EPOCH, &registry));
        let nodes = certificate
            .full_path(proposer, &registry)
            .expect("registered identities");
        assert!(nodes
            .iter()
            .eq(wallets.iter().map(|wallet| &wallet.address)));
        assert_eq!(certificate.paths.len(), hops);

        let mut hop_messages = Vec::with_capacity(hops);
        let mut signer_keys = Vec::with_capacity(2 * hops);
        for (hop, edge) in route.paths.iter().zip(nodes.windows(2)) {
            assert_eq!((&hop.from, &hop.to), (&edge[0], &edge[1]));
            // The prefix is generated by the production path builder and already binds
            // the transaction hash, chain ID, epoch and ordered path through the sender.
            let mut message = TRAIL_TX_PATH_DOMAIN.to_vec();
            message.extend(hex::decode(&hop.prefix).expect("production prefix"));
            for address in edge {
                message.extend(Hasher::hash(address.as_bytes().to_vec()));
                signer_keys.push(registry.public_key(address).expect("registered signer key"));
            }
            hop_messages.push(message);
        }
        let fixture = Self {
            wallets,
            hop_messages,
            signer_keys,
            aggregate: Wallet::bls_signature_from_string(certificate.signature)
                .expect("production signature"),
        };

        // Check the prepared messages against each independent production hop signature.
        let mut individual = Vec::with_capacity(2 * hops);
        fixture.sign_hops(&mut individual);
        assert_eq!(individual.len(), 2 * hops);
        for (pair, hop) in individual.chunks_exact(2).zip(&route.paths) {
            assert_eq!(
                format!("0x{}", hex::encode(pair[0].to_bytes())),
                hop.sender_signature
            );
            assert_eq!(
                format!("0x{}", hex::encode(pair[1].to_bytes())),
                *hop.receiver_signature.as_ref().unwrap()
            );
        }
        assert_eq!(
            aggregate(&individual).to_bytes(),
            fixture.aggregate.to_bytes()
        );
        let verify_messages = fixture.verification_messages();
        assert!(Wallet::bls_aggregated_verify_parsed(
            verify_messages
                .iter()
                .map(|message| message.to_vec())
                .collect(),
            fixture.signer_keys.clone(),
            fixture.aggregate,
        ));
        fixture
    }

    fn sign_hops(&self, output: &mut Vec<Signature>) {
        for (keys, message) in self.wallets.windows(2).zip(&self.hop_messages) {
            for wallet in keys {
                output.push(wallet.bls_private_key.sign(message, &[], &[]));
            }
        }
    }

    fn verification_messages(&self) -> Vec<&[u8]> {
        self.hop_messages
            .iter()
            .flat_map(|message| [message.as_slice(); 2])
            .collect()
    }
}

fn aggregate(individual: &[Signature]) -> Signature {
    // Match Wallet::bls_aggregated_sign, including validation of points being added.
    let mut combined = AggregateSignature::from_signature(&individual[0]);
    for signature in &individual[1..] {
        combined
            .add_signature(signature, true)
            .expect("new valid hop signature");
    }
    combined.to_signature()
}

fn verify(aggregate: &Signature, messages: &[&[u8]], keys: &[&PublicKey]) -> bool {
    // Same BLST method, domain tag and group checks as Wallet::bls_aggregated_verify_parsed.
    aggregate.aggregate_verify(true, messages, &[], keys, true) == BLST_ERROR::BLST_SUCCESS
}

struct Sample {
    signing_ns: u128,
    aggregation_ns: u128,
    verification_ns: u128,
}

fn measure(fixture: &Fixture, count: usize) -> Vec<Sample> {
    let mut signatures = Vec::with_capacity(fixture.signer_keys.len());
    let reference = fixture.aggregate.to_bytes();
    let mut measured = Vec::with_capacity(count);
    for i in 0..WARMUP + count {
        signatures.clear();
        let start = Instant::now();
        black_box(fixture).sign_hops(&mut signatures);
        let signed = Instant::now();
        let combined = black_box(aggregate(black_box(&signatures)));
        let finished = Instant::now();
        assert_eq!(signatures.len(), fixture.signer_keys.len());
        assert_eq!(
            combined.to_bytes(),
            reference,
            "timed signature differs from valid certificate"
        );
        if i >= WARMUP {
            measured.push(Sample {
                signing_ns: (signed - start).as_nanos(),
                aggregation_ns: (finished - signed).as_nanos(),
                verification_ns: 0,
            });
        }
    }

    let messages = fixture.verification_messages();
    let keys: Vec<_> = fixture.signer_keys.iter().collect();
    for i in 0..WARMUP + count {
        let start = Instant::now();
        let valid = black_box(verify(
            black_box(&fixture.aggregate),
            black_box(&messages),
            black_box(&keys),
        ));
        let elapsed = start.elapsed();
        assert!(valid, "BLST rejected the production certificate");
        if i >= WARMUP {
            measured[i - WARMUP].verification_ns = elapsed.as_nanos();
        }
    }
    measured
}

fn nearest_rank(sorted: &[u128], percentile: usize) -> u128 {
    let rank = (sorted.len() * percentile).div_ceil(100);
    sorted[rank - 1]
}

fn open_csv(directory: &Path, filename: &str, header: &str) -> io::Result<BufWriter<File>> {
    let mut output = BufWriter::new(
        OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(directory.join(filename))?,
    );
    writeln!(output, "{header}")?;
    Ok(output)
}

type TimingField = fn(&Sample) -> u128;
const TIMINGS: [(&str, TimingField); 4] = [
    ("signing_total", |s| s.signing_ns + s.aggregation_ns),
    ("bls_signing", |s| s.signing_ns),
    ("bls_aggregation", |s| s.aggregation_ns),
    ("bls_verification", |s| s.verification_ns),
];

fn write_results(directory: &Path, results: &[(usize, Vec<Sample>)]) -> io::Result<()> {
    let mut raw = open_csv(
        directory,
        "samples.csv",
        "hops,sample,hop_signatures,signing_ns,aggregation_ns,signing_total_ns,verification_ns",
    )?;
    let mut summary = open_csv(
        directory,
        "summary.csv",
        "hops,operation,hop_signatures,warmups,samples,mean_us,p95_us,p99_us",
    )?;
    for (hops, samples) in results {
        let signatures = 2 * hops;
        for (index, sample) in samples.iter().enumerate() {
            writeln!(
                raw,
                "{hops},{},{signatures},{},{},{},{}",
                index + 1,
                sample.signing_ns,
                sample.aggregation_ns,
                sample.signing_ns + sample.aggregation_ns,
                sample.verification_ns
            )?;
        }
        for (operation, field) in TIMINGS {
            let mut values: Vec<_> = samples.iter().map(field).collect();
            values.sort_unstable();
            let mean = values.iter().sum::<u128>() as f64 / values.len() as f64 / 1000.0;
            let p95 = nearest_rank(&values, 95) as f64 / 1000.0;
            let p99 = nearest_rank(&values, 99) as f64 / 1000.0;
            writeln!(
                summary,
                "{hops},{operation},{signatures},{WARMUP},{},{mean:.6},{p95:.6},{p99:.6}",
                values.len()
            )?;
        }
    }
    raw.flush()?;
    summary.flush()
}

fn proc_field<'a>(contents: &'a str, name: &str) -> Option<&'a str> {
    contents
        .lines()
        .filter_map(|line| line.split_once(':'))
        .find_map(|(key, value)| (key.trim() == name).then(|| value.trim()))
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();
    if cfg!(debug_assertions) || args.samples < MIN_SAMPLES {
        return Err("run in release mode with at least 1000 samples per hop count".into());
    }
    for name in ["samples.csv", "summary.csv", "environment.json"] {
        let file = args.output_dir.join(name);
        if file.try_exists()? {
            return Err(format!("output already exists: {}", file.display()).into());
        }
    }
    let compiler = Command::new("rustc").arg("--version").output()?;
    if !compiler.status.success() {
        return Err("rustc --version failed".into());
    }
    let cpuinfo = fs::read_to_string("/proc/cpuinfo").unwrap_or_default();
    let status = fs::read_to_string("/proc/self/status").unwrap_or_default();
    let environment = json!({
        "cpu_model": proc_field(&cpuinfo, "model name"),
        "host_logical_cpus": cpuinfo.lines().filter(|line| line.split_once(':').is_some_and(|(key, _)| key.trim() == "processor")).count(),
        "process_cpu_affinity": proc_field(&status, "Cpus_allowed_list"),
        "process_available_parallelism": std::thread::available_parallelism()?.get(),
        "benchmark_driver_threads": 1,
        "rustc": String::from_utf8(compiler.stdout)?.trim(),
        "build_mode": "release",
        "arch": std::env::consts::ARCH,
        "os": std::env::consts::OS,
        "hops": HOPS,
        "warmups_per_operation_and_hop_count": WARMUP,
        "samples_per_operation_and_hop_count": args.samples,
        "percentile_method": "nearest_rank",
        "verification_cache": false,
    });

    let mut results = Vec::with_capacity(HOPS.len());
    for hops in HOPS {
        let fixture = Fixture::new(hops);
        results.push((hops, measure(&fixture, args.samples)));
        eprintln!(
            "Completed {hops} hops ({} samples per operation)",
            args.samples
        );
    }
    fs::create_dir_all(&args.output_dir)?;
    write_results(&args.output_dir, &results)?;
    let mut output = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(args.output_dir.join("environment.json"))?;
    serde_json::to_writer_pretty(&mut output, &environment)?;
    writeln!(output)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn production_fixtures_have_two_signatures_per_hop() {
        for hops in HOPS {
            let fixture = Fixture::new(hops);
            let keys: Vec<_> = fixture.signer_keys.iter().collect();
            let messages = fixture.verification_messages();
            assert_eq!(keys.len(), hops * 2);
            assert_eq!(messages.len(), keys.len());
            assert_eq!(fixture.aggregate.to_bytes().len(), 48);
            assert!(verify(&fixture.aggregate, &messages, &keys));
        }
    }

    #[test]
    fn direct_verification_rejects_changed_signed_statement() {
        let fixture = Fixture::new(4);
        let keys: Vec<_> = fixture.signer_keys.iter().collect();
        let mut messages = fixture.verification_messages();
        let mut changed = messages[0].to_vec();
        changed[TRAIL_TX_PATH_DOMAIN.len()] ^= 1;
        messages[..2].fill(&changed);
        assert!(!verify(&fixture.aggregate, &messages, &keys));
        assert!(verify(
            &fixture.aggregate,
            &fixture.verification_messages(),
            &keys
        ));
    }

    #[test]
    fn nearest_rank_takes_the_actual_order_statistics() {
        let samples: Vec<u128> = (1..=1000).map(|n| n * n).collect();
        assert_eq!(nearest_rank(&samples, 95), 950 * 950);
        assert_eq!(nearest_rank(&samples, 99), 990 * 990);
        assert_eq!(nearest_rank(&[1, 2, 3], 95), 3);
    }
}
